    final langMap = _tables[language] ?? _en;
    return langMap[key] ?? _en[key] ?? key;
  }

  /// Interpolate `{name}` style placeholders.
  String tr(String key, [Map<String, String>? params]) {
    var s = t(key);
    if (params != null) {
      params.forEach((k, v) {
        s = s.replaceAll('{$k}', v);
      });
    }
    return s;
  }

